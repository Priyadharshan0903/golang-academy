// Command enumgen generates String, Parse and text marshaling methods
// for an integer "enum" type: a named integer type with constants. It
// is the example generator for lesson 14.3, and runs from a
// go:generate directive:
//
//	//go:generate go run ../enumgen -type=Color
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/constant"
	"go/format"
	"go/importer"
	"go/parser"
	"go/token"
	"go/types"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"text/template"
)

func main() {
	typeName := flag.String("type", "", "name of the enum type (required)")
	flag.Parse()
	if *typeName == "" {
		fmt.Fprintln(os.Stderr, "enumgen: -type is required")
		os.Exit(2)
	}
	src, err := generate(".", *typeName)
	if err != nil {
		fmt.Fprintln(os.Stderr, "enumgen:", err)
		os.Exit(1)
	}
	out := strings.ToLower(*typeName) + "_enum.go"
	if err := os.WriteFile(out, src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "enumgen:", err)
		os.Exit(1)
	}
}

// [start generate]

type value struct {
	Name  string // Go name, such as ColorRed
	Text  string // text form, such as "red"
	Value string // the constant's value
}

// generate type-checks the package in dir and returns the source of the
// generated file for typeName.
func generate(dir, typeName string) ([]byte, error) {
	fset := token.NewFileSet()
	var files []*ast.File
	paths, _ := filepath.Glob(filepath.Join(dir, "*.go"))
	for _, p := range paths {
		if strings.HasSuffix(p, "_test.go") || strings.HasSuffix(p, "_enum.go") {
			continue // never read our own output, or tests
		}
		f, err := parser.ParseFile(fset, p, nil, 0)
		if err != nil {
			return nil, err
		}
		files = append(files, f)
	}
	if len(files) == 0 {
		return nil, fmt.Errorf("no Go files in %s", dir)
	}

	// The type checker computes every constant's value, including iota
	// expressions, so the generator never has to guess.
	conf := types.Config{Importer: importer.Default()}
	pkg, err := conf.Check(files[0].Name.Name, fset, files, nil)
	if err != nil {
		return nil, err
	}
	obj := pkg.Scope().Lookup(typeName)
	if obj == nil {
		return nil, fmt.Errorf("type %s not found", typeName)
	}
	named, ok := obj.Type().(*types.Named)
	if !ok || named.Underlying().(*types.Basic).Info()&types.IsInteger == 0 {
		return nil, fmt.Errorf("%s is not a named integer type", typeName)
	}

	var values []value
	for _, name := range pkg.Scope().Names() {
		c, ok := pkg.Scope().Lookup(name).(*types.Const)
		if !ok || !types.Identical(c.Type(), named) {
			continue
		}
		values = append(values, value{
			Name:  name,
			Text:  strings.ToLower(strings.TrimPrefix(name, typeName)),
			Value: c.Val().ExactString(),
		})
	}
	slices.SortStableFunc(values, func(a, b value) int {
		x, _ := constant.Int64Val(constant.MakeFromLiteral(a.Value, token.INT, 0))
		y, _ := constant.Int64Val(constant.MakeFromLiteral(b.Value, token.INT, 0))
		return int(x - y)
	})

	var buf bytes.Buffer
	err = tmpl.Execute(&buf, map[string]any{
		"Package": pkg.Name(),
		"Type":    typeName,
		"Values":  values,
		"Command": "go run ../enumgen -type=" + typeName,
	})
	if err != nil {
		return nil, err
	}
	return format.Source(buf.Bytes()) // gofmt the output, so it never shows up in a diff as unformatted
}

// [end generate]

// [start template]

var tmpl = template.Must(template.New("enum").Parse(`// Code generated by "{{.Command}}"; DO NOT EDIT.

package {{.Package}}

import "fmt"

// String returns the text form of v.
func (v {{.Type}}) String() string {
	switch v {
	{{- range .Values}}
	case {{.Name}}:
		return "{{.Text}}"
	{{- end}}
	}
	return fmt.Sprintf("{{.Type}}(%d)", int(v))
}

// Parse{{.Type}} returns the {{.Type}} whose text form is s.
func Parse{{.Type}}(s string) ({{.Type}}, error) {
	switch s {
	{{- range .Values}}
	case "{{.Text}}":
		return {{.Name}}, nil
	{{- end}}
	}
	return 0, fmt.Errorf("invalid {{.Type}} %q", s)
}

// {{.Type}}Values returns every defined {{.Type}}, in order.
func {{.Type}}Values() []{{.Type}} {
	return []{{.Type}}{ {{- range .Values}}{{.Name}}, {{end -}} }
}

// MarshalText implements encoding.TextMarshaler, so JSON, flags and
// slog use the text form.
func (v {{.Type}}) MarshalText() ([]byte, error) { return []byte(v.String()), nil }

// UnmarshalText implements encoding.TextUnmarshaler.
func (v *{{.Type}}) UnmarshalText(b []byte) error {
	p, err := Parse{{.Type}}(string(b))
	if err != nil {
		return err
	}
	*v = p
	return nil
}
`))

// [end template]
